/*有N个鱼塘排成一排（N < 100），每个鱼塘中有一定数量的鱼，例如：N = 5时，如下表：
	即：在第1个鱼塘中钓鱼第1分钟内可钓到10条鱼，第2分钟内只能钓到8条鱼，……，第5分钟以后再也钓不到鱼了。
	从第1个鱼塘到第2个鱼塘需要3分钟，从第2个鱼塘到第3个鱼塘需要5分钟，……
	给出一个截止时间T(T < 1000)，设计一个钓鱼方案，从第1个鱼塘出发，希望能钓到最多的鱼。
	假设能钓到鱼的数量仅和已钓鱼的次数有关，且每次钓鱼的时间都是整数分钟。
	输入描述
	共5行，分别表示：
	第1行为N；
	第2行为第1分钟各个鱼塘能钓到的鱼的数量，每个数据之间用一空格隔开；
	第3行为每过1分钟各个鱼塘钓鱼数的减少量，每个数据之间用一空格隔开；
	第4行为当前鱼塘到下一个相邻鱼塘需要的时间；
	第5行为截止时间T。
	输出描述
	一个整数（不超过231?1），表示你的方案能钓到的最多的鱼。
	用例输入 1
	5
	10 14 20 16 9
	2 4 6 5 3
	3 5 4 4
	14
	用例输出 1
	76
	*/
#include<stdio.h>
#include<string.h>

int num(char a[],int n,int number[])
{
    int count=0,i,j;
    char *s=a;
    int temp=0;
    
    // 第一部分：统计数字个数
    for(i=0;i<=n;i++)
    {
        if(*(s+i)>='0' && *(s+i)<='9')
        {
            temp = 1;            
        }
        if((*(s+i) < '0' || *(s+i) >'9') && temp==1)
        {
            count++;
            temp=0; 
        }
        if(*(s+i) == '\0' && temp==1)
            count++; 
    }
    
    // 第二部分：提取数字
    i=0;
    j=0;
    while(i<=n)
    {
        // 跳过非数字字符
        while(i<=n && (*(s+i)<'0' || *(s+i)>'9'))
        {
            i++;
        }
        
        // 如果找到数字
        if(i<=n && *(s+i)>='0' && *(s+i)<='9')
        {
            int sum=0;
            // 提取连续的数字
            while(i<=n && *(s+i)>='0' && *(s+i)<='9')
            {
                sum=sum*10+(*(s+i)-'0');
                i++;
            }
            
            // 存储所有提取到的数字（包括0）
            number[j]=sum;
            j++;
        }
    }
    return count;
}

int main()
{
    char a[] = "012A123x456 17960? 302tab0";
    int b=strlen(a);
    int number[13];
    int c = num(a,b,number);
    int i;
    printf("%d\n",c);
    for(i=0;i<c;i++)
    {
        printf("%d ",number[i]);
    }
    return 0;
}
